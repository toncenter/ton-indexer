// gramstat-stake-registry checks captured historical account states and generates
// the aggregator's identity registry and the browser's compact code/address list.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"time"

	"github.com/toncenter/ton-indexer/ton-index-go/internal/gramstat/handlers/validators"
)

type capture struct {
	Family       string          `json:"family"`
	Holder       string          `json:"holder"`
	Since        uint32          `json:"utime_since"`
	MC           uint32          `json:"anchor_mc_seqno"`
	Root         string          `json:"anchor_root_hash"`
	File         string          `json:"anchor_file_hash"`
	ResponseHash string          `json:"response_sha256"`
	Body         json.RawMessage `json:"body"`
	Error        string          `json:"error"`
	Inventory    *struct {
		Checks     int   `json:"checks"`
		CapturedAt int64 `json:"captured_at"`
	} `json:"inventory"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run() error {
	input := flag.String("capture", "", "JSONL account-state capture")
	registryPath := flag.String("registry", "", "output JSON identity registry")
	uiPath := flag.String("ui", "", "output browser module")
	fixtures := flag.String("fixtures", "", "optional output fixture directory")
	flag.Parse()
	if *input == "" || *registryPath == "" || *uiPath == "" {
		return fmt.Errorf("--capture, --registry and --ui are required")
	}
	f, err := os.Open(*input)
	if err != nil {
		return err
	}
	defer f.Close()
	dec := json.NewDecoder(f)
	byHolder := map[string][]validators.Affiliation{}
	firstBodies := map[string]capture{}
	var expected, checks int
	var checkedAt string
	for {
		var c capture
		if err = dec.Decode(&c); err == io.EOF {
			break
		} else if err != nil {
			return err
		}
		if c.Inventory != nil {
			expected = c.Inventory.Checks
			checkedAt = time.Unix(c.Inventory.CapturedAt, 0).UTC().Format(time.RFC3339)
			continue
		}
		checks++
		if c.Error != "" {
			return fmt.Errorf("capture contains an RPC error for %s", c.Holder)
		}
		a, e := validators.InspectAffiliation(c.Body, validators.Round{Since: c.Since, AnchorMC: c.MC, AnchorRoot: c.Root, AnchorFile: c.File}, c.Holder, c.Family)
		if e != nil {
			return fmt.Errorf("holder %s MC %d: %w", c.Holder, c.MC, e)
		}
		// The capture records the original HTTP body digest before JSONL encoding.
		if len(c.ResponseHash) != 64 {
			return fmt.Errorf("missing original response digest")
		}
		a.ResponseHash = c.ResponseHash
		if a.Protocol == "" {
			continue
		}
		key := a.Holder + "/" + a.Family
		byHolder[key] = append(byHolder[key], a)
		if _, ok := firstBodies[a.Protocol]; !ok {
			firstBodies[a.Protocol] = c
		}
	}
	if expected == 0 || checks != expected {
		return fmt.Errorf("incomplete capture: %d of %d", checks, expected)
	}
	registry := validators.AffiliationRegistry{CheckedAt: checkedAt}
	for _, observations := range byHolder {
		sort.Slice(observations, func(i, j int) bool { return observations[i].MC < observations[j].MC })
		first, last := observations[0], observations[len(observations)-1]
		for _, a := range observations {
			if a.Pool != first.Pool || a.Protocol != first.Protocol || a.CodeHash != first.CodeHash {
				return fmt.Errorf("changing holder identity: %s", a.Holder)
			}
		}
		last.FirstMC, last.FirstResponseHash = first.MC, first.ResponseHash
		registry.Entries = append(registry.Entries, last)
	}
	sort.Slice(registry.Entries, func(i, j int) bool {
		a, b := registry.Entries[i], registry.Entries[j]
		if a.Protocol != b.Protocol {
			return a.Protocol < b.Protocol
		}
		return a.Holder < b.Holder
	})
	data, err := json.MarshalIndent(registry, "", "  ")
	if err != nil {
		return err
	}
	if err = os.WriteFile(*registryPath, append(data, '\n'), 0644); err != nil {
		return err
	}
	type group struct {
		Protocol string   `json:"protocol"`
		Pool     string   `json:"pool"`
		CodeHash string   `json:"codeHash"`
		Holders  []string `json:"holders"`
	}
	groups := map[string]*group{}
	var ordered []*group
	counts := map[string]int{}
	for _, a := range registry.Entries {
		key := a.Protocol + "/" + a.Pool + "/" + a.CodeHash
		if groups[key] == nil {
			g := &group{Protocol: a.Protocol, Pool: a.Pool, CodeHash: a.CodeHash}
			groups[key] = g
			ordered = append(ordered, g)
		}
		groups[key].Holders = append(groups[key].Holders, a.Holder)
		counts[a.Protocol]++
	}
	data, err = json.MarshalIndent(ordered, "", "  ")
	if err != nil {
		return err
	}
	module := "// Generated by gramstat-stake-registry from checked historical account states.\nexport const STAKE_REGISTRY_AS_OF = " + strconvJSON(checkedAt) + ";\nexport const STAKE_CONTRACTS = " + string(data) + ";\n"
	if err = os.WriteFile(*uiPath, []byte(module), 0644); err != nil {
		return err
	}
	if *fixtures != "" {
		if err = os.MkdirAll(*fixtures, 0755); err != nil {
			return err
		}
		for _, protocol := range []string{"Stakee", "Hipo", "Whales wsTON"} {
			c, ok := firstBodies[protocol]
			if !ok {
				return fmt.Errorf("missing fixture protocol %s", protocol)
			}
			data, err = json.MarshalIndent(c, "", "  ")
			if err != nil {
				return err
			}
			if err = os.WriteFile(filepath.Join(*fixtures, strings.ToLower(strings.ReplaceAll(protocol, " ", "-"))+".json"), append(data, '\n'), 0644); err != nil {
				return err
			}
		}
	}
	fmt.Printf("checked=%d verified_holders=%d protocols=%v\n", checks, len(registry.Entries), counts)
	return nil
}

func strconvJSON(s string) string { b, _ := json.Marshal(s); return string(b) }
