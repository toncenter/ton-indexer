//! Calls every kind of the ton_v1 extension on every block and tells what it
//! answered, a line per call. Made for the stub backend of ton-tvm-router,
//! whose answers are known (router/stub.go): a test of the way from a module
//! through fireton to the router and back.
//!
//! Two calls of the host per block: a batch of every kind of call, among them
//! invalid ones, then a get-method on the state the first batch gave, as a
//! module gives back a state it got.

// The handlers of substreams::handlers are exported functions that read their
// input behind a pointer of the host, and keep no attribute of ours.
#![allow(clippy::not_unsafe_ptr_arg_deref)]

// Generated by buffa: names and shapes are those of the .proto files, some
// of which the module does not use.
#[allow(clippy::all, dead_code)]
mod pb {
    include!(concat!(env!("OUT_DIR"), "/probe.v1.mod.rs"));
}

mod account_check;
mod emulate_check;
mod get_method_check;
mod rston_check;
mod tx_point_check;

use std::iter::once;

use buffa::Enumeration;
use substreams::errors::Error;
use substreams_ton::oneof::account;
use substreams_ton::pb::ton::tvm::v1::{CallResult, ContextOverrides};
use substreams_ton::rston::cell::HashBytes;
use substreams_ton::stack::StackExt;
use substreams_ton::tvm::{self, EmulationOutcome, GetMethodCall, Outcome};
use substreams_ton::types::BlockLazyView;
use substreams_ton::{At, StdAddr};

const ELECTOR: StdAddr = StdAddr::new(-1, HashBytes([0x33; 32]));

/// An external message to the elector with an empty body.
const EXTERNAL_TO_ELECTOR: &str =
    "b5ee9c7201010101002500004589fe666666666666666666666666666666666666666666666666666666666666666604";

#[substreams::handlers::map]
fn map_probe(block: &BlockLazyView<'_>) -> Result<pb::Probe, Error> {
    let block = substreams_ton::block(block)?;
    let mc = block.masterchain_block.as_option().ok_or_else(|| Error::msg("no masterchain block"))?;
    let mc_id = mc.id.as_option().ok_or_else(|| Error::msg("no masterchain block id"))?;

    // Some account changed in this round, else the elector.
    let changed = once(mc)
        .chain(block.shard_blocks.iter())
        .find_map(|data| {
            let workchain = data.id.as_option()?.shard_id.as_option()?.workchain_id;
            let account = data.extra.as_option()?.account_blocks.first()?;
            address(workchain, &account.account_addr)
        })
        .unwrap_or(ELECTOR);
    let external = hex::decode(EXTERNAL_TO_ELECTOR)?;

    let mut batch = tvm::batch();
    batch
        .get_account(&ELECTOR)
        .add(tvm::get_account(&changed).at(At::BeforeBlock))
        .add(tvm::get_account(&ELECTOR).at(At::BeforeTx(1)))
        .get_method(&ELECTOR, "active_election_id")
        .add(tvm::emulate(external.clone()).ignore_chksig())
        .add(tvm::emulate(external).shard_account(vec![0xb5]))
        .add(
            tvm::get_method(&ELECTOR, "seqno")
                .context(ContextOverrides { block_rand_seed: Some(vec![0; 32]), ..Default::default() }),
        )
        .add(tvm::get_method(&StdAddr::new(0, HashBytes([0; 32])), "seqno").gas_limit(u64::MAX));
    let results = batch.execute()?;

    let clock_matches = match &results[0].outcome {
        Some(Outcome::Account(snapshot)) => {
            snapshot.block.as_option().is_some_and(|b| b.seq_no == mc_id.seq_no && b.root_hash == mc_id.root_hash)
        }
        _ => false,
    };
    let given_state = match &results[0].outcome {
        Some(Outcome::Account(snapshot)) => snapshot.value.as_option().and_then(|v| v.shard_account_boc.clone()),
        _ => None,
    };

    let mut lines: Vec<String> = results.into_iter().map(describe).collect();
    match given_state {
        Some(boc) => {
            lines.push(describe(tvm::execute(vec![GetMethodCall::on_shard_account(boc, "seqno").into()])?.remove(0)))
        }
        None => lines.push("no state to give back".to_string()),
    }
    Ok(pb::Probe { mc_seqno: mc_id.seq_no, clock_matches, results: lines, ..Default::default() })
}

fn describe(result: CallResult) -> String {
    match &result.outcome {
        Some(Outcome::Error(error)) => {
            let code = error.code.as_known().map_or("unknown code", |code| code.proto_name());
            format!("error {code}: {}", error.message)
        }
        Some(Outcome::Account(snapshot)) => {
            let kind =
                match snapshot.value.as_option().and_then(|v| v.account.as_option()).and_then(|a| a.kind.as_ref()) {
                    Some(account::Kind::AccountNone(_)) => "none",
                    Some(account::Kind::Account(_)) => "existing",
                    None => "unset",
                };
            let seqno = snapshot.block.as_option().map_or(0, |b| b.seq_no);
            format!("account {kind} in block {seqno}")
        }
        Some(Outcome::GetMethod(_)) => match result.get_method() {
            Ok(out) => format!("get_method exit {} first {:?}", out.exit_code, out.stack.int(0).ok()),
            Err(e) => format!("get_method: {e}"),
        },
        Some(Outcome::Emulate(_)) => match result.emulate() {
            Ok(EmulationOutcome::Executed(executed)) => {
                format!("executed lt {}", executed.transaction.as_option().map_or(0, |t| t.lt))
            }
            Ok(EmulationOutcome::ExternalNotAccepted(rejected)) => {
                format!("external not accepted, exit {}", rejected.vm_exit_code)
            }
            Err(e) => format!("emulate: {e}"),
        },
        None => "no outcome".to_string(),
    }
}

/// The address of an account of a block: the workchain of its shard and its
/// account_addr.
pub(crate) fn address(workchain: i32, account_addr: &[u8]) -> Option<StdAddr> {
    Some(StdAddr::new(workchain.try_into().ok()?, HashBytes(account_addr.try_into().ok()?)))
}
