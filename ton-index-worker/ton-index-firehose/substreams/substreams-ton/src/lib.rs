/// The block of a handler, decoded whole from its lazy view.
///
/// A handler takes the block as `&types::BlockLazyView<'_>` and calls this,
/// never as `types::Block`: substreams decodes an input taken by value under
/// the budget that buffa keeps against untrusted input, 32 MiB of decoded
/// elements, and the heaviest TON blocks are over it (round 3,295,441 of
/// spring 2020, with 929 shard blocks, is 50 MB), so the module would fail on
/// them. A lazy view decodes each subtree under a budget of its own.
pub fn block(view: &types::BlockLazyView<'_>) -> Result<types::Block, buffa::DecodeError> {
    buffa::view::LazyMessageView::to_owned_message(view)
}
