//! TON jetton transfers: the transfer messages (transfer#0f8a7ea5) that jetton
//! wallets received, found as the index finds them (tondb-scanner:
//! JettonWalletDetectorR and ActionDetector).
//!
//! - A candidate is a transaction whose inbound message has the opcode of
//!   transfer.
//! - Its account is a jetton wallet of a master when get_wallet_data of the
//!   account after the round gives its owner and the master, and
//!   get_wallet_address of the master after the round derives the account for
//!   that owner. Two batches of ton_v1 calls a round, one call per wallet each.
//! - The body is read by TEP-74; one that does not parse is no transfer, nor is
//!   a transaction that is not an ordinary one.
//!
//! Unlike the index, a forward payload stored in the body itself is given too,
//! as a cell of its own: the index keeps only a referenced one.

// The handlers of substreams::handlers are exported functions that read their
// input behind a pointer of the host, and keep no attribute of ours.
#![allow(clippy::not_unsafe_ptr_arg_deref)]

// Generated by buffa: names and shapes are those of the .proto files, some
// of which the module does not use.
#[allow(clippy::all, dead_code)]
mod pb {
    include!(concat!(env!("OUT_DIR"), "/jettons.v1.mod.rs"));
}

use std::collections::{BTreeMap, BTreeSet};

use buffa::view::LazyMessageView;
use substreams::errors::Error;
use substreams_ton::oneof::{common_msg_info, msg_address_int, transaction_descr};
use substreams_ton::rston::boc::Boc;
use substreams_ton::rston::cell::{CellBuilder, Load};
use substreams_ton::rston::models::AnyAddr;
use substreams_ton::rston::num::Tokens;
use substreams_ton::stack::{self, StackExt};
use substreams_ton::tvm;
use substreams_ton::types::{BlockLazyView, Transaction};
use substreams_ton::StdAddr;

const TRANSFER: u32 = 0x0f8a7ea5;

#[substreams::handlers::map]
fn map_jetton_transfers(block: &BlockLazyView<'_>) -> Result<pb::JettonTransfers, Error> {
    // the transactions with a transfer message in, with their accounts
    let mut candidates = Vec::new();
    for account in block.account_blocks() {
        let account = account?;
        let Some(address) = account.address() else { continue };
        for tx in &account.view.transactions {
            let tx = tx?;
            if tx.in_msg.get()?.is_some_and(|msg| msg.opcode == Some(TRANSFER)) {
                candidates.push((address.clone(), tx.to_owned_message()?));
            }
        }
    }
    let mut out = pb::JettonTransfers { mc_seqno: block.seqno()?, ..Default::default() };
    let masters = masters(candidates.iter().map(|(wallet, _)| wallet))?;
    for (wallet, tx) in &candidates {
        if let Some(master) = masters.get(wallet) {
            out.transfers.extend(transfer(wallet, master, tx));
        }
    }
    Ok(out)
}

/// The masters of the jetton wallets among the accounts, after the round:
/// get_wallet_data of an account gives its owner and master, and the master's
/// get_wallet_address must derive the account for that owner.
fn masters<'a>(accounts: impl Iterator<Item = &'a StdAddr>) -> Result<BTreeMap<StdAddr, StdAddr>, Error> {
    let accounts: BTreeSet<&StdAddr> = accounts.collect();
    let mut batch = tvm::batch();
    for account in &accounts {
        batch.get_method(account, "get_wallet_data");
    }
    // (wallet, owner, master) as the accounts tell them
    let mut claimed = Vec::new();
    for (account, result) in accounts.iter().zip(batch.execute()?) {
        // A call error, as on an account that is not active, is no wallet.
        let Ok(data) = result.get_method() else { continue };
        // balance:int owner:slice master:slice code:cell, as the index requires
        let typed = success(data.exit_code) && data.stack.int(0).is_ok() && data.stack.cell_boc(3).is_ok();
        if let (true, Ok(Some(owner)), Ok(Some(master))) = (typed, data.stack.address(1), data.stack.address(2)) {
            claimed.push(((*account).clone(), owner, master));
        }
    }
    let mut batch = tvm::batch();
    for (_, owner, master) in &claimed {
        batch.add(tvm::get_method(master, "get_wallet_address").arg(stack::address(owner)));
    }
    let mut masters = BTreeMap::new();
    for ((wallet, _, master), result) in claimed.into_iter().zip(batch.execute()?) {
        let Ok(derived) = result.get_method() else { continue };
        if success(derived.exit_code) && derived.stack.address(0).ok().flatten().as_ref() == Some(&wallet) {
            masters.insert(wallet, master);
        }
    }
    Ok(masters)
}

/// As run_get_method of TON: exit codes 0 and 1 are a success.
fn success(exit_code: i32) -> bool {
    exit_code == 0 || exit_code == 1
}

/// The transfer that a transaction of a wallet received; none when its body is
/// not one, or the transaction is not an ordinary one.
fn transfer(wallet: &StdAddr, master: &StdAddr, tx: &Transaction) -> Option<pb::JettonTransfer> {
    let msg = tx.in_msg.as_option()?;
    let Some(common_msg_info::Kind::IntMsgInfo(info)) = &msg.info.kind else { return None };
    let source = match info.src.kind.as_ref()? {
        msg_address_int::Kind::AddrStd(src) => raw(src.workchain_id, &src.address),
        msg_address_int::Kind::AddrVar(src) => raw(src.workchain_id, &src.address),
    };
    let Some(transaction_descr::Kind::TransOrd(ord)) = &tx.description.kind else { return None };

    // transfer#0f8a7ea5 query_id:uint64 amount:(VarUInteger 16) destination:MsgAddress
    //   response_destination:MsgAddress custom_payload:(Maybe ^Cell)
    //   forward_ton_amount:(VarUInteger 16) forward_payload:(Either Cell ^Cell)
    let body = Boc::decode(msg.body.boc.as_deref()?).ok()?;
    let mut cs = body.as_slice().ok()?;
    if cs.load_u32().ok()? != TRANSFER {
        return None;
    }
    let query_id = cs.load_u64().ok()?;
    let amount = Tokens::load_from(&mut cs).ok()?;
    let destination = AnyAddr::load_from(&mut cs).ok()?;
    let response_destination = AnyAddr::load_from(&mut cs).ok()?;
    let custom_payload = if cs.load_bit().ok()? { Some(cs.load_reference_cloned().ok()?) } else { None };
    let forward_ton_amount = Tokens::load_from(&mut cs).ok()?;
    let forward_payload = if cs.load_bit().ok()? {
        Some(cs.load_reference_cloned().ok()?)
    } else if cs.size_bits() > 0 || cs.size_refs() > 0 {
        Some(CellBuilder::build_from(cs).ok()?)
    } else {
        None
    };

    Some(pb::JettonTransfer {
        trace_id: tx.trace_id.clone(),
        transaction_hash: tx.hash.clone(),
        transaction_lt: tx.lt,
        transaction_now: tx.now,
        transaction_aborted: ord.aborted,
        query_id,
        amount: amount.into_inner().to_string(),
        source,
        destination: any_raw(&destination),
        jetton_wallet: raw(wallet.workchain.into(), &wallet.address.0),
        jetton_master: raw(master.workchain.into(), &master.address.0),
        response_destination: any_raw(&response_destination),
        custom_payload: custom_payload.map(|cell| Boc::encode(&cell)),
        forward_ton_amount: forward_ton_amount.into_inner().to_string(),
        forward_payload: forward_payload.map(|cell| Boc::encode(&cell)),
        ..Default::default()
    })
}

/// The raw form of the index and of API v3: 0:HEX.
fn raw(workchain: i32, address: &[u8]) -> String {
    format!("{workchain}:{}", hex::encode_upper(address))
}

/// An address of a body in raw form, addr_none as the index writes it; empty
/// for an external one.
fn any_raw(address: &AnyAddr) -> String {
    match address {
        AnyAddr::Std(address) => raw(address.workchain.into(), &address.address.0),
        AnyAddr::Var(address) => raw(address.workchain, &address.address),
        AnyAddr::None => "addr_none".to_string(),
        AnyAddr::Ext(_) => String::new(),
    }
}
